def conns(times, size=None, jitter=0, seed=1):
    rnd = random.Random(seed)
    out = []
    for i, t in enumerate(times):
        b = None if size is None else size + rnd.randint(-jitter, jitter)
        out.append({"id": i, "opened_at": t, "closed_at": t + 1, "local_port": 40000 + i,
                    "bytes_sent": None if b is None else b // 3,
                    "bytes_recv": None if b is None else b - b // 3})
    return out


class BeaconStatsTests(unittest.TestCase):
    def test_perfect_period(self):
        b = beacon_stats([1000 + 60 * i for i in range(20)], poll=2)
        self.assertAlmostEqual(b["interval"], 60)
        self.assertAlmostEqual(b["cv"], 0)
        self.assertEqual((b["checkins"], b["missed"]), (20, 0))

    def test_jitter(self):
        rnd = random.Random(7)
        times, t = [], 1000.0
        for _ in range(30):
            t += 60 * (1 + rnd.uniform(-0.08, 0.08))
            times.append(t)
        b = beacon_stats(times, poll=2)
        self.assertLess(b["cv"], 0.06)
        self.assertGreater(b["cv"], 0.01)

    def test_missed_checkins_are_not_irregularity(self):
        times = [1000 + 60 * i for i in range(30) if i not in (5, 6, 17)]
        b = beacon_stats(times, poll=2)
        self.assertEqual(b["missed"], 3)
        self.assertAlmostEqual(b["cv"], 0, places=6)
        self.assertEqual(b["samples"], 30)

    def test_long_silence_is_a_pause_not_missed_checkins(self):
        # Ten check-ins, the machine sleeps two hours, ten more: still every 60 s.
        times = [1000 + 60 * i for i in range(10)] + [9000 + 60 * i for i in range(10)]
        b = beacon_stats(times, poll=2)
        # 18 regular intervals in two runs of ten: twenty check-ins in all.
        self.assertEqual((b["missed"], b["samples"], len(b["pauses"])), (0, 20, 1))
        self.assertAlmostEqual(b["cv"], 0)
        fs = beacon_findings(conns(times), 2, "x")
        self.assertIn("1 pause (longest 2h 4m) left out", fs[0]["reason"])  # 9000 - 1540 s
        self.assertNotIn("missed", fs[0]["reason"])

    def test_bursts_merge_into_one_checkin(self):
        times = []
        for i in range(10):
            times += [1000 + 60 * i, 1000 + 60 * i + 0.5]  # two sockets per check-in
        self.assertEqual(beacon_stats(times, poll=2)["checkins"], 10)

    def test_too_few_or_too_fast(self):
        self.assertIsNone(beacon_stats([1000 + 60 * i for i in range(5)], poll=2))
        self.assertIsNone(beacon_stats([1000 + 4 * i for i in range(50)], poll=2))

    def test_random_traffic_scores_nothing(self):
        rnd = random.Random(3)
        times, t = [], 0.0
        for _ in range(40):
            t += rnd.expovariate(1 / 120)
            times.append(t)
        self.assertEqual(beacon_findings(conns(times), 2, "tcp 1.2.3.4:443"), [])


class CheckTests(unittest.TestCase):
    def test_beacon_findings_explain_themselves(self):
        fs = beacon_findings(conns([1000 + 60 * i for i in range(20)], size=1200, jitter=20),
                             2, "tcp 198.51.100.20:4444")
        reasons = [f["reason"] for f in fs]
        self.assertTrue(reasons[0].startswith("Periodic: every 60 s ± 0% (coefficient of variation 0.00"))
        self.assertIn("Kept up for 19m 0s", reasons[1])
        self.assertTrue(reasons[2].startswith("Similar size each time: ≈ 1.2 kB ± "))
        self.assertEqual(fs[0]["points"], scoring.POINTS["beacon_regularity"])
        self.assertTrue(all(f["check"] == "beacon" for f in fs))
        self.assertIn("198.51.100.20:4444", fs[0]["data"])
        self.assertIn("sock_diag", fs[2]["data"])
        self.assertLessEqual(sum(f["points"] for f in fs), 65)  # never alerts on its own

    def test_loose_period(self):
        rnd = random.Random(11)
        times, t = [], 0.0
        for _ in range(30):
            t += 60 * (1 + rnd.uniform(-0.45, 0.45))
            times.append(t)
        fs = beacon_findings(conns(times), 2, "x")
        self.assertTrue(fs[0]["reason"].startswith("Loosely periodic"))
        self.assertLess(fs[0]["points"], scoring.POINTS["beacon_regularity"] / 2)

    def test_long_connection(self):
        short = [{"id": 1, "opened_at": 0, "closed_at": 1800, "local_port": 1}]
        self.assertIsNone(scoring.long_connection_finding(short, now=5000, baseline=None))
        live = [{"id": 2, "opened_at": 100, "closed_at": None, "local_port": 5}]
        f = scoring.long_connection_finding(live, now=100 + 2 * 3600, baseline=100)
        self.assertIn("at least 2h 0m", f["reason"])
        self.assertIn("still open", f["reason"])
        self.assertAlmostEqual(f["points"], 15 + 15 * (3600 / (7 * 3600)), places=1)
        very = scoring.long_connection_finding(live, now=100 + 30 * 3600, baseline=None)
        self.assertEqual(very["points"], scoring.POINTS["long_connection"])

    def test_location(self):
        f = scoring.location_findings({"exe": "/tmp/.x/agent (deleted)", "exe_deleted": True,
                                       "pid": 7}, "/tmp/.x/agent")
        self.assertEqual([x["points"] for x in f], [25, 10])
        self.assertIn("world-writable", f[0]["reason"])
        f = scoring.location_findings({"exe": "/usr/bin/python3.11", "pid": 8},
                                      "/usr/bin/python3.11 /home/a/.cache/up.py")
        self.assertEqual(f[0]["reason"], "Runs from a hidden directory (/home/a/.cache/up.py)")
        self.assertEqual(scoring.location_findings({"exe": "/home/a/.local/bin/tool"},
                                                   "/home/a/.local/bin/tool"), [])
        self.assertEqual(scoring.location_findings({"exe": "/usr/bin/curl"}, "/usr/bin/curl"), [])


class AllowlistTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.al = Allowlist(os.path.join(self.tmp.name, "allowlist.json"))

    def tearDown(self):
        self.tmp.cleanup()

    def pair(self, program="/usr/bin/x", ip="203.0.113.5", port=443, proto="tcp", direction="out"):
        return {"program": program, "ip": ip, "port": port, "proto": proto, "direction": direction}

    def test_builtins(self):
        self.assertEqual(self.al.match(self.pair(proto="udp", port=123))["id"], "builtin-ntp")
        self.assertEqual(self.al.match(self.pair(ip="192.168.1.1", port=53))["id"], "builtin-dns-lan")
        self.assertIsNone(self.al.match(self.pair(ip="8.8.8.8", port=53)))  # external DNS: scored
        self.assertEqual(self.al.match(self.pair(ip="127.0.0.1", port=8765))["id"],
                         "builtin-loopback")
        self.assertEqual(self.al.match(self.pair(program="/usr/sbin/NetworkManager", port=80))["id"],
                         "builtin-networkmanager")
        # Allowlisting follows the real executable path, not the name.
        self.assertIsNone(self.al.match(self.pair(program="/tmp/NetworkManager", port=80)))

    def test_user_rules_persist_and_validate(self):
        rule = self.al.add({"program": AGENT, "ip": "198.51.100.0/24", "port": "4444",
                            "proto": "tcp", "reason": "lab sample, known"}, now=5)
        self.assertEqual(rule["id"], "user-1")
        self.assertEqual(self.al.match(self.pair(program=AGENT, ip="198.51.100.20", port=4444))["id"],
                         "user-1")
        self.assertIsNone(self.al.match(self.pair(program=AGENT, ip="198.51.100.20", port=443)))
        with open(os.path.join(self.tmp.name, "allowlist.json")) as fh:
            self.assertEqual(json.load(fh)["rules"][0]["reason"], "lab sample, known")
        for bad, msg in [({"program": "x"}, "reason"), ({"ip": "nope", "reason": "r"}, "ip"),
                         ({"port": 70000, "reason": "r"}, "port"),
                         ({"proto": "icmp", "program": "x", "reason": "r"}, "proto"),
                         ({"reason": "everything"}, "must name")]:
            with self.subTest(bad=bad), self.assertRaisesRegex(ValueError, msg):
                self.al.add(bad)
        self.assertTrue(self.al.remove("user-1"))
        self.assertFalse(self.al.remove("user-1"))
        self.assertTrue(self.al.remove("builtin-ntp"))  # built-ins can be switched off
        self.assertIsNone(self.al.match(self.pair(proto="udp", port=123)))
        self.assertFalse(self.al.remove("builtin-nonsense"))


class ScorerEndToEndTests(unittest.TestCase):
    """Synthetic histories through tracker and scorer, as the monitor runs them."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.store = Store(os.path.join(self.tmp.name, "v.db"))
        self.tracker = Tracker(self.store)
        self.allow = Allowlist(os.path.join(self.tmp.name, "allowlist.json"))
        self.scorer = Scorer(self.store, self.allow, poll_interval=2)
        self.agent = dict(proc(7000, AGENT, "agent"), exe="/tmp/.x/agent")
        self.ff = proc(4410, FF, "firefox")
        self.chrony = proc(800, CHRONY, "chronyd", uid=0, user="root")
        # Baseline: firefox already talking to two known destinations; the second
        # connection closes right after, so only the first is long-lived.
        self.known = sock("198.51.100.30", 443, 9000, FF, 4410, local_port=30000)
        brief = sock("198.51.100.31", 443, 9001, FF, 4410, local_port=30001)
        self.tracker.ingest(snap(0, [self.known, brief], [self.ff]))

    def tearDown(self):
        self.store.close()
        self.tmp.cleanup()

    def beacon(self, t0, period, n, make):
        """Run the tracker through n check-ins, each seen in exactly one poll."""
        for i in range(n):
            t = t0 + period * i
            s = make(i)
            self.tracker.ingest(snap(t, [self.known, s], [self.ff, self.agent, self.chrony]))
            self.tracker.ingest(snap(t + 2, [self.known], [self.ff, self.agent, self.chrony]))

    def score_of(self, program, ip, port):
        row = self.store.one("SELECT * FROM scores WHERE program=? AND ip=? AND port=?",
                             (program, ip, port))
        row["findings"] = json.loads(row["findings"])
        return row

    def test_dropper_beacon_alerts_with_reasons(self):
        self.beacon(1000, 60, 20, lambda i: dict(
            sock("198.51.100.20", 4444, 5000 + i, AGENT, 7000, local_port=41000 + i),
            bytes_sent=400 + i % 3, bytes_recv=820))
        result = self.scorer.run(now=1000 + 60 * 20)
        self.assertEqual(result["new_alerts"], 1)
        sc = self.score_of(AGENT, "198.51.100.20", 4444)
        self.assertEqual(sc["score"], 100)
        checks = {f["check"] for f in sc["findings"]}
        # Not "rarity": 20 contacts is not rare, even from a single program.
        self.assertEqual(checks, {"beacon", "first_seen", "uncommon_port", "process_location"})
        for f in sc["findings"]:
            self.assertTrue(f["reason"] and f["data"] and f["at"])
        alert = self.store.one("SELECT * FROM alerts")
        self.assertEqual((alert["status"], alert["port"]), ("open", 4444))
        ev = self.store.one("SELECT * FROM events WHERE kind='alert'")
        self.assertTrue(ev["summary"].startswith("Alert, score 100: agent → tcp 198.51.100.20:4444."))
        self.assertIn("threshold 70", ev["source"])

        # Re-running does not duplicate; a dismissal sticks.
        self.store.db.execute("UPDATE alerts SET status='dismissed'")
        self.assertEqual(self.scorer.run(now=1000 + 60 * 21)["new_alerts"], 0)
        self.assertEqual(self.store.one("SELECT COUNT(*) n FROM alerts")["n"], 1)
        self.assertEqual(self.store.one("SELECT status FROM alerts")["status"], "dismissed")

        # The graph and node details carry the score and its reasons.
        g = self.tracker.graph(now=1000 + 60 * 21, window=86400,
                               scopes=("reserved", "internet", "lan"))
        agent_node = [p for p in g["programs"] if p["key"] == AGENT][0]
        self.assertEqual(agent_node["score"], 100)
        detail = self.tracker.program_detail(AGENT)
        self.assertEqual(detail["findings"][0]["alert_status"], "dismissed")

    def test_one_alert_per_program_and_address(self):
        # The dropper reaches the same server on two ports: one alert, both ports listed.
        self.beacon(1000, 60, 20, lambda i: sock("198.51.100.20", 4444 if i % 2 else 8443,
                                                 5000 + i, AGENT, 7000, local_port=41000 + i))
        self.scorer.run(now=1000 + 60 * 20)
        alerts = self.store.query("SELECT * FROM alerts")
        self.assertEqual(len(alerts), 1)
        self.assertEqual(json.loads(alerts[0]["ports"]), ["tcp/4444", "tcp/8443"])
        self.assertEqual(alerts[0]["fingerprint"], f"{AGENT}|198.51.100.20|out")
        self.assertEqual(len(self.store.query("SELECT * FROM scores WHERE program=?", (AGENT,))), 2)

    def test_allowlisted_beacon_scores_but_never_alerts(self):
        self.beacon(1000, 64, 20, lambda i: sock("198.51.100.123", 123, 6000 + i, CHRONY, 800,
                                                 proto="udp", local_port=42000 + i, uid=0))
        self.assertEqual(self.scorer.run(now=1000 + 64 * 20)["new_alerts"], 0)
        sc = self.store.one("SELECT * FROM scores WHERE program=?", (CHRONY,))
        self.assertGreater(sc["score"], 40)  # still periodic, and visibly so
        self.assertEqual(json.loads(sc["allowlisted"])["id"], "builtin-ntp")
        self.assertEqual(self.store.query("SELECT * FROM alerts"), [])

    def test_beacon_to_known_destination_stays_below_threshold(self):
        # A regular poll by a long-known program to a destination known since baseline.
        self.beacon(1000, 300, 20, lambda i: sock("198.51.100.31", 443, 7000 + i, FF, 4410,
                                                  local_port=43000 + i))
        self.scorer.run(now=1000 + 300 * 20)
        sc = self.score_of(FF, "198.51.100.31", 443)
        self.assertEqual({f["check"] for f in sc["findings"]}, {"beacon"})
        self.assertLess(sc["score"], scoring.ALERT_THRESHOLD)
        self.assertEqual(self.store.query("SELECT * FROM alerts"), [])

    def test_unattributed_short_connections_still_reveal_a_beacon(self):
        # Each check-in is only ever seen in TIME_WAIT; the kernel timer dates it.
        for i in range(15):
            close = 1000 + 90 * i + 0.3
            poll = close + 1.7  # the next poll happens a little later each time
            tw = dict(sock("198.51.100.21", 8081, 0, uid=1000, state="TIME_WAIT",
                           local_port=44000 + i), closed_ago=poll - close)
            self.tracker.ingest(snap(poll, [self.known, tw], [self.ff]))
        self.scorer.run(now=1000 + 90 * 15)
        sc = self.score_of("hidden:closed", "198.51.100.21", 8081)
        beacon = [f for f in sc["findings"] if f["check"] == "beacon"][0]
        self.assertIn("every 90 s ± 0%", beacon["reason"])
        row = self.store.one("SELECT * FROM connections WHERE program='hidden:closed' LIMIT 1")
        self.assertAlmostEqual(row["opened_at"], 1000.3)
        self.assertIn("TIME_WAIT timer", row["close_note"])

    def test_tracked_connection_close_time_refined_by_time_wait(self):
        a = sock("198.51.100.40", 443, 8000, FF, 4410, local_port=45000)
        self.tracker.ingest(snap(100, [self.known, a], [self.ff]))
        tail = dict(sock("198.51.100.40", 443, 0, uid=0, state="TIME_WAIT", local_port=45000),
                    closed_ago=1.25)
        self.tracker.ingest(snap(102, [self.known, tail], [self.ff]))
        row = self.store.one("SELECT * FROM connections WHERE inode=8000")
        self.assertAlmostEqual(row["closed_at"], 100.75)

    def test_rarity_of_a_one_off_internet_destination(self):
        # One connection to a public address no other program uses. (9.9.9.9 is a
        # public resolver; the connection itself is synthetic.)
        one = sock("9.9.9.9", 443, 9200, FF, 4410, local_port=47000)
        self.tracker.ingest(snap(50, [self.known, one], [self.ff]))
        self.scorer.run(now=60)
        sc = self.score_of(FF, "9.9.9.9", 443)
        rarity = [f for f in sc["findings"] if f["check"] == "rarity"][0]
        self.assertEqual(rarity["reason"], "Rare: only this program has ever contacted this"
                                           " address (1 connection in Vigil's history)")
        self.assertEqual({f["check"] for f in sc["findings"]}, {"first_seen", "rarity"})

    def test_long_ssh_session(self):
        ssh = sock("203.0.113.10", 22, 9100, "/usr/bin/ssh", 6000, local_port=46000)
        sshp = proc(6000, "/usr/bin/ssh", "ssh")
        self.tracker.ingest(snap(10, [self.known, ssh], [self.ff, sshp]))
        self.tracker.ingest(snap(10 + 3 * 3600, [self.known, ssh], [self.ff, sshp]))
        self.scorer.run(now=10 + 3 * 3600)
        sc = self.score_of("/usr/bin/ssh", "203.0.113.10", 22)
        long_f = [f for f in sc["findings"] if f["check"] == "long_connection"][0]
        self.assertIn("One connection open 3h 0m", long_f["reason"])
        self.assertLess(sc["score"], scoring.ALERT_THRESHOLD)

    def test_user_allowlist_suppresses_new_alerts(self):
        self.allow.add({"program": AGENT, "port": 4444, "reason": "lab sample"})
        self.beacon(1000, 60, 20, lambda i: sock("198.51.100.20", 4444, 5000 + i, AGENT, 7000,
                                                 local_port=41000 + i))
        self.assertEqual(self.scorer.run(now=1000 + 60 * 20)["new_alerts"], 0)
        sc = self.store.one("SELECT * FROM scores WHERE program=?", (AGENT,))
        self.assertGreaterEqual(sc["score"], scoring.ALERT_THRESHOLD)
        self.assertEqual(json.loads(sc["allowlisted"])["reason"], "lab sample")


