class IocTests(unittest.TestCase):
    def scan(self, blob, hashes=False):
        iocs = inspector.Iocs()
        iocs.scan(blob, "test", hashes=hashes)
        return {(i["type"], i["value"]) for i in iocs.items.values()}

    def test_extraction(self):
        found = self.scan(b"see http://198.51.100.7/a.php?x=1, mail bob@evil.example or "
                          b"203.0.113.5; c2 update.badhost.xyz; config.xml word.rels "
                          b"LibreOffice/24.2.7.2 version 1.2.3.4.5 System.IO", hashes=True)
        self.assertIn(("url", "http://198.51.100.7/a.php?x=1"), found)
        self.assertIn(("email", "bob@evil.example"), found)
        self.assertIn(("ip", "203.0.113.5"), found)
        self.assertIn(("domain", "update.badhost.xyz"), found)
        values = {v for _, v in found}
        for noise in ("198.51.100.7", "config.xml", "word.rels", "24.2.7.2", "1.2.3.4"):
            self.assertNotIn(noise, values)

    def test_utf16_and_hashes(self):
        blob = b"\0\0" + "http://198.51.100.9/x".encode("utf-16-le") + b"\0\0"
        self.assertIn(("url", "http://198.51.100.9/x"), self.scan(blob))
        h = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        self.assertIn(("sha256", h), self.scan(h.encode(), hashes=True))
        self.assertNotIn(("sha256", h), self.scan(h.encode()))
        self.assertEqual(self.scan(b"0" * 64, hashes=True), set())

    def test_cap(self):
        iocs = inspector.Iocs()
        iocs.scan(" ".join(f"http://198.51.100.1/{i}" for i in range(400)).encode(), "t")
        self.assertEqual(len(iocs.items), inspector.IOC_MAX)
        self.assertTrue(iocs.truncated)


class SafetyTests(unittest.TestCase):
    def test_no_code_execution_imports(self):
        for module in (inspector, ole):
            src = Path(module.__file__).read_text()
            for bad in (r"\bimport subprocess\b", r"\bos\.system\b", r"\bexec\(", r"\beval\(",
                        r"\bimportlib\b", r"\bpickle\b", r"\bmarshal\b", r"\bctypes\b",
                        r"\bos\.startfile\b", r"\bwebbrowser\b"):
                self.assertNotRegex(src, bad, f"{module.__name__} must not use {bad}")

    def test_inspection_runs_nothing_and_writes_nothing(self):
        real_open = builtins.open

        def guarded_open(file, mode="r", *a, **k):
            if any(c in mode for c in "wax+"):
                raise AssertionError(f"inspector tried to write {file}")
            return real_open(file, mode, *a, **k)

        samples = [(b(), n) for n, b, *_ in SuspiciousSampleTests.CASES]
        samples += [(synth.SHELL_DROPPER, "install.sh"), (synth.FAKE_PE, "invoice.pdf.exe")]
        with tempfile.TemporaryDirectory() as tmp:
            cwd = os.getcwd()
            os.chdir(tmp)
            try:
                with mock.patch("subprocess.Popen", side_effect=AssertionError("spawned")), \
                        mock.patch("os.system", side_effect=AssertionError("spawned")), \
                        mock.patch("os.execv", side_effect=AssertionError("exec")), \
                        mock.patch("builtins.open", guarded_open):
                    for data, name in samples:
                        inspect(data, name)
            finally:
                os.chdir(cwd)
            self.assertEqual(os.listdir(tmp), [])


class RobustnessTests(unittest.TestCase):
    def test_truncated_and_corrupt_inputs(self):
        rnd = random.Random(9)
        inputs = [synth.docm_dropper()[:3000], synth.doc_legacy_macro()[:1500],
                  ole.MAGIC + bytes(rnd.getrandbits(8) for _ in range(4000)),
                  b"%PDF-1.7\nstream\n\x78\x9c garbage endstream", b"PK\x03\x04broken",
                  b"{\\rtf1{\\object\\objdata zz}}", b"", bytes(rnd.getrandbits(8) for _ in range(5000))]
        for i, data in enumerate(inputs):
            with self.subTest(i):
                r = inspect(data, f"file{i}.bin")
                self.assertIn(r["verdict"], dict(inspector.VERDICTS).values())

    def test_oversized_member_is_skipped_not_expanded(self):
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("huge.bin", b"\0" * (inspector.MEMBER_MAX + 1024))
        r = inspect(buf.getvalue(), "bomb.zip")
        self.assertNotIn("nested", r["details"])
        self.assertTrue(any("too large" in l for l in r["limits"]))


class ContextTests(unittest.TestCase):
    def test_feed_hits_and_network_history(self):
        from vigil.net.enrich import Enricher
        with tempfile.TemporaryDirectory() as tmp:
            store = Store(os.path.join(tmp, "v.db"))
            en = Enricher(store, tmp)
            en.import_feed("urlhaus", b'# x\n"1","2026-10-29","http://198.51.100.20/stage2.ps1",'
                                      b'"online","","malware_download","","https://urlhaus.abuse.ch/url/1/",""\n',
                           "fixture")
            with store.lock, store.db:
                store.db.execute("INSERT INTO destinations VALUES('198.51.100.20','reserved',100,200)")
            r = inspect(synth.docm_dropper(), "invoice.docm")
            r = inspector.link_context(r, store, en)
            by_check = {f["check"]: f for f in r["findings"]}
            self.assertIn("lists (malware_download)", by_check["threat_intel"]["reason"])
            self.assertIn("This PC has connected to 198.51.100.20", by_check["seen_on_network"]["reason"])
            saved = inspector.save(store, r, "test")
            row = store.one("SELECT * FROM inspections WHERE id=?", (saved["id"],))
            self.assertEqual((row["verdict"], row["sha256"]), (r["verdict"], r["hashes"]["sha256"]))
            self.assertEqual(json.loads(row["report"])["id"], saved["id"])
            store.close()


class IocOffsetTests(unittest.TestCase):
    def test_offsets_point_into_the_original_bytes(self):
        # SYNTHETIC binary: noise around an address and a URL; offsets must survive the strings pass.
        from vigil.files import inspector as ins
        blob = b"\x00\x01\xff" * 50 + b"connect 203.0.113.9 now" + b"\x00" * 7 + b"get https://dl.dropper-test.net/x.sh\x00" \
            + "wide 198.51.100.4".encode("utf-16-le") + b"\x02"
        iocs = ins.Iocs()
        iocs.scan(blob, "file")
        where = {v["value"]: v["where"] for v in iocs.items.values()}
        self.assertEqual(where["203.0.113.9"], f"file at offset {blob.index(b'203.0.113.9'):#x}")
        self.assertEqual(where["https://dl.dropper-test.net/x.sh"], f"file at offset {blob.index(b'https://'):#x}")
        wide = blob.index("198.51.100.4".encode("utf-16-le"))
        self.assertEqual(where["198.51.100.4"], f"file (UTF-16 text) at offset {wide:#x}")


    def test_loopback_mentions_are_not_network_evidence(self):
        from vigil.files import inspector as ins
        store = mock.Mock()
        store.one.return_value = {"first_seen": 1.0, "last_seen": 2.0}
        report = {"iocs": [{"type": "ip", "value": "127.0.0.1", "where": "x"},
                           {"type": "ip", "value": "203.0.113.9", "where": "y"}],
                  "findings": [], "score": 0}
        ins.link_context(report, store)
        seen = [f["reason"] for f in report["findings"] if f["check"] == "seen_on_network"]
        self.assertEqual(len(seen), 1)
        self.assertIn("203.0.113.9", seen[0])


