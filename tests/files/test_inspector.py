def inspect(data, name):
    return inspector.inspect_bytes(data, name)


def checks(report):
    return {f["check"] for f in report["findings"] if f["points"] > 0}


class OvbaTests(unittest.TestCase):
    def test_spec_examples(self):
        # MS-OVBA 3.2.1 (no compression) and 3.2.2 (normal compression).
        self.assertEqual(ole.decompress(bytes.fromhex(
            "0119B000616263646566676800696A6B6C6D6E6F7000717273747576 2E".replace(" ", ""))),
            b"abcdefghijklmnopqrstuv.")
        self.assertEqual(ole.decompress(bytes.fromhex(
            "012FB000236161616263646582660070616768696A01380861"
            "6B6C00306D6E6F700671027004107273747576107778797A003C")),
            b"#aaabcdefaaaaghijaaaaaklaaamnopqaaaaaaaaaaaarstuvwxyzaaa")

    def test_round_trip_with_independent_compressor(self):
        rnd = random.Random(5)
        for data in (b"", b"x", synth.DROPPER_VBA.encode() * 7,
                     bytes(rnd.getrandbits(8) for _ in range(10000)), b"a" * 9000):
            self.assertEqual(ole.decompress(synth.ovba_compress(data)), data)

    def test_rejects_garbage(self):
        with self.assertRaises(ole.OleError):
            ole.decompress(b"\x02junk")
        with self.assertRaises(ole.OleError):  # copy token pointing before the chunk
            ole.decompress(b"\x01" + struct.pack("<H", 0xB000 | 3) + b"\x01" + struct.pack("<H", 0xF000))


class OleTests(unittest.TestCase):
    def test_reads_files_written_by_libreoffice(self):
        doc = ole.OleFile((FILES / "benign.doc").read_bytes())
        names = {"/".join(p) for p in doc.streams()}
        self.assertTrue({"WordDocument", "1Table", "\x01CompObj"} <= names)
        for path in doc.streams():
            self.assertEqual(len(doc.read(path)), doc.entries[doc.paths[path]]["size"])
        xls = ole.OleFile((FILES / "benign.xls").read_bytes())
        self.assertIn(("Workbook",), xls.streams())
        self.assertTrue(xls.read(("Workbook",)).startswith(b"\x09\x08"))  # BIFF8 BOF record

    def test_vba_modules_with_text_offsets(self):
        f = ole.OleFile(synth.vba_bin({"ThisDocument": synth.DROPPER_VBA, "Module1": synth.BENIGN_VBA}))
        mods = {m["name"]: m for m in ole.vba_modules(f)}
        self.assertEqual(mods["ThisDocument"]["source"], synth.DROPPER_VBA)
        self.assertEqual(mods["Module1"]["source"], synth.BENIGN_VBA)
        self.assertEqual(mods["Module1"]["stream"], "VBA/Module1")

    def test_large_streams_use_regular_sectors(self):
        big = bytes(range(256)) * 40  # 10 kB, above the 4 kB mini-stream cutoff
        f = ole.OleFile(synth.build_ole({("Big",): big, ("Small",): b"tiny"}))
        self.assertEqual(f.read(("Big",)), big)
        self.assertEqual(f.read(("Small",)), b"tiny")

    def test_hostile_structures_fail_cleanly(self):
        with self.assertRaises(ole.OleError):
            ole.OleFile(b"not an ole file" * 100)
        data = bytearray(synth.build_ole({("Big",): b"x" * 10000}))
        fat_sector = struct.unpack_from("<I", data, 0x4C)[0]
        struct.pack_into("<I", data, 512 * (fat_sector + 1), 0)  # sector 0 now chains to itself
        with self.assertRaises(ole.OleError):
            ole.OleFile(bytes(data)).read(("Big",))


class BenignTests(unittest.TestCase):
    """Real, ordinary documents must not be flagged, and nothing is ever called safe."""

    def test_libreoffice_documents(self):
        for path in sorted(FILES.glob("benign.*")):
            with self.subTest(path.name):
                r = inspect(path.read_bytes(), path.name)
                self.assertEqual(r["verdict"], "No suspicious indicators found")
                self.assertLess(r["score"], 10)
                self.assertTrue(any("never opened, run or rendered" in l for l in r["limits"]))
                text = json.dumps(r).lower()
                self.assertNotRegex(text, r"\bsafe\b|\bclean\b")
                self.assertFalse([i for i in r["iocs"] if i["type"] == "ip"])  # no version-string IPs

    def test_namespaces_are_not_iocs(self):
        r = inspect((FILES / "benign.docx").read_bytes(), "benign.docx")
        self.assertGreater(r["ignored_format_urls"], 10)
        self.assertEqual(r["iocs"], [])

    def test_plain_files(self):
        for data, name in ((b"Shopping list: eggs, milk, bread.\n", "list.txt"),
                           (b"#!/bin/sh\necho hello\nls -la\n", "hello.sh"),
                           (b"\x89PNG\r\n\x1a\n" + b"\0" * 64, "photo.png")):
            with self.subTest(name):
                r = inspect(data, name)
                self.assertLess(r["score"], 30, r["findings"])


class SuspiciousSampleTests(unittest.TestCase):
    CASES = [
        # name, builder, verdict, checks that must be present
        ("invoice.docm", synth.docm_dropper, "Likely malicious",
         {"macros", "macro_autoexec", "macro_behaviour", "download_cradle", "hidden_powershell"}),
        ("notes.docx", synth.docx_with_benign_macro, "Suspicious", {"macros", "type_mismatch"}),
        ("letter.docx", synth.docx_remote_template, "Suspicious", {"remote_template"}),
        ("order.docx", synth.docx_follina, "Likely malicious", {"remote_object"}),
        ("memo.docx", synth.docx_dde, "Likely malicious", {"dde"}),
        ("budget.xlsm", synth.xlsm_xlm, "Likely malicious", {"xlm_macro", "macro_autoexec"}),
        ("report.doc", synth.doc_legacy_macro, "Likely malicious", {"macros", "macro_autoexec"}),
        ("sheet.xls", synth.xls_hidden_xlm, "Likely malicious", {"xlm_macro", "macro_autoexec"}),
        ("scan.pdf", synth.pdf_autorun_js, "Likely malicious", {"pdf_javascript", "pdf_autorun"}),
        ("scan2.pdf", synth.pdf_obfuscated, "Likely malicious", {"pdf_obfuscation", "pdf_autorun"}),
        ("scan3.pdf", synth.pdf_hidden_in_objstm, "Likely malicious",
         {"pdf_javascript", "pdf_autorun", "pdf_obfuscation"}),
        ("scan4.pdf", synth.pdf_launch_embedded, "Likely malicious", {"pdf_launch", "pdf_embedded"}),
        ("scan5.pdf", synth.pdf_with_appended_exe, "Suspicious", {"pdf_structure"}),
        ("eq.rtf", synth.rtf_equation, "Likely malicious", {"rtf_object", "embedded_object"}),
        ("cv.doc", synth.rtf_malformed_header, "Likely malicious", {"rtf_object", "rtf_structure",
                                                                      "type_mismatch"}),
        ("delivery.zip", synth.zip_delivery, "Likely malicious", {"disguise", "encrypted"}),
        ("Invoice.lnk", synth.lnk_powershell, "Likely malicious", {"download_cradle", "file_type"}),
        ("invoice.html", synth.html_smuggling, "Suspicious", {"html_smuggling"}),
    ]

    def test_samples(self):
        for name, build, verdict, must in self.CASES:
            with self.subTest(name):
                r = inspect(build(), name)
                self.assertEqual(r["verdict"], verdict, r["findings"])
                self.assertLessEqual(must, checks(r))
                for f in r["findings"]:
                    self.assertTrue(f["reason"] and f["data"], f)

    def test_scripts(self):
        r = inspect(synth.SHELL_DROPPER, "install.sh")
        self.assertEqual(r["verdict"], "Likely malicious")
        self.assertLessEqual({"pipe_to_shell", "temp_exec", "persistence"}, checks(r))
        r = inspect(synth.PS1_CRADLE, "run.ps1")
        self.assertLessEqual({"download_cradle", "hidden_powershell"}, checks(r))

    def test_macro_details_are_reported(self):
        r = inspect(synth.docm_dropper(), "invoice.docm")
        mod = r["details"]["macros"][0]
        self.assertEqual(mod["name"], "ThisDocument")
        self.assertIn("Sub AutoOpen()", mod["source"])
        self.assertTrue(any(h.startswith("auto-runs: AutoOpen (line 2)") for h in mod["hits"]))
        auto = [f for f in r["findings"] if f["check"] == "macro_autoexec"][0]
        self.assertEqual(auto["data"], "VBA module ThisDocument, line 2")
        urls = [i["value"] for i in r["iocs"] if i["type"] == "url"]
        self.assertIn("http://198.51.100.20/stage2.ps1", urls)

    def test_remote_template_ioc_and_local_template(self):
        r = inspect(synth.docx_remote_template(), "letter.docx")
        self.assertIn("https://198.51.100.88/templates/invoice.dotm",
                      [i["value"] for i in r["iocs"]])
        self.assertIn("bare IP", r["findings"][0]["reason"])
        parts = synth.word_parts()
        parts["word/_rels/settings.xml.rels"] = (
            '<Relationships><Relationship Id="r1" Type="http://schemas.openxmlformats.org/'
            'officeDocument/2006/relationships/attachedTemplate" Target="file:///C:/Users/a/'
            'Templates/Normal.dotm" TargetMode="External"/></Relationships>')
        r = inspect(synth.ooxml(parts), "ordinary.docx")
        self.assertEqual(r["verdict"], "No suspicious indicators found")

    def test_nested_archive_member_details(self):
        r = inspect(synth.zip_delivery(), "delivery.zip")
        nested = {n["name"]: n for n in r["details"]["nested"]}
        self.assertEqual(nested["invoice_2026.pdf.exe"]["type"], "pe")
        self.assertNotIn("secret/locked.docm", nested)  # encrypted: not read
        self.assertTrue(any("Password-protected" in l for l in r["limits"]))


